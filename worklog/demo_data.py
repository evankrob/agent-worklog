def materialize(root: Path, now: datetime | None = None) -> Path:
    """Write the demo tree and return the config path."""
    if now is None:
        moment = datetime.now().astimezone()
    elif now.tzinfo is None:
        moment = now.astimezone()
    else:
        moment = now
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    _write_config(root)
    _write_claude(root, moment)
    _write_grok(root, moment)
    _write_deliverables(root)
    return root / "worklog.toml"


def _iso(moment: datetime) -> str:
    return moment.isoformat(timespec="seconds")


def _at(now: datetime, days_ago: int, hour: int, minute: int) -> datetime:
    local = now if now.tzinfo else now.astimezone()
    shifted = local - timedelta(days=days_ago)
    return shifted.replace(hour=hour, minute=minute, second=0, microsecond=0)


